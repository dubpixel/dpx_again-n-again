#!/bin/sh
# ================================================================================
# SHELL SCRIPT - GENERATE AN "AGAIN" LAUNCHER APP FROM ANY INSTALLED APP
# ================================================================================
# PROJECT: dpx_again-n-again
# ================================================================================
#
# File: make-again.sh
# Purpose: Given /path/to/Some App 1.2.app, build "~/Applications/SomeAppAgain.app",
#          a launcher that opens a NEW instance (open -n) of that app. If the name
#          ends in a version number, the launcher always opens the highest
#          installed "Some App <version>.app" (the same trick as dpx_tr_again).
#          Built locally, so macOS never quarantines it.
# Usage:   make-again.sh [--exact] [--out DIR] /path/to/App.app
#            --exact   never generalize the version; always open that exact app
#            --out DIR install somewhere other than ~/Applications
# Prints:  the path of the app it created (last line of stdout).
# Dependencies: macOS (open, osascript, defaults, sips optional)
#
# CHANGE LOG: see CHANGELOG.md
#
# ================================================================================
set -eu

OUT="$HOME/Applications"
EXACT=0
while [ $# -gt 0 ]; do
  case "$1" in
    --exact) EXACT=1; shift ;;
    --out)   OUT="$2"; shift 2 ;;
    --)      shift; break ;;
    -*)      echo "unknown option: $1" >&2; exit 2 ;;
    *)       break ;;
  esac
done
[ $# -eq 1 ] || { echo "usage: make-again.sh [--exact] [--out DIR] /path/to/App.app" >&2; exit 2; }

SRC="${1%/}"
case "$SRC" in *.app) ;; *) echo "not an app bundle (needs .app): $SRC" >&2; exit 1 ;; esac
[ -d "$SRC" ] || { echo "no such app: $SRC" >&2; exit 1; }

NAME=$(basename "$SRC" .app)

# Strip a trailing version ("Foo 3.5.2", "Foo v2", "Foo-1.0") to get the STEM.
# Only generalize when something was actually stripped and a stem remains.
STEM=$(printf '%s' "$NAME" | sed -E 's/[ _-]+[vV]?[0-9]+([._-][0-9A-Za-z]+)*$//')
if [ "$EXACT" -eq 1 ] || [ -z "$STEM" ] || [ "$STEM" = "$NAME" ]; then
  MODE=exact; STEM="$NAME"
else
  MODE=latest
fi

# Never wrap one of our own launchers (they are marked by their bundle id).
case "$(defaults read "$SRC/Contents/Info" CFBundleIdentifier 2>/dev/null || true)" in
  tv.dubpixel.again.*) echo "refusing: '$NAME' is already an Again launcher" >&2; exit 1 ;;
esac

# Strip characters that can't live safely in a quoted shell string or a filename.
case "$STEM" in *"'"*|*'"'*|*'`'*|*'$'*|*'\'*|*'/'*) echo "app name has characters I won't embed in a script: $STEM" >&2; exit 1 ;; esac

# Output name has NO spaces ("Tessera Remote" -> "TesseraRemoteAgain") so it can
# never match the "STEM.app" / "STEM <digit>.app" search patterns of any launcher.
APPNAME="$(printf '%s' "$STEM" | tr -d ' ')Again"
APP="$OUT/$APPNAME.app"
SRCDIR=$(dirname "$SRC")

mkdir -p "$OUT"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
BIN="$APP/Contents/MacOS/Again"

# --- the generated launcher ------------------------------------------------
{
  echo '#!/bin/sh'
  echo "# Generated by dpx_again-n-again for: $NAME ($MODE)"
  echo "STEM='$STEM'"
  echo "MODE='$MODE'"
  echo "ORIG='$SRC'"
  echo "HINT='$SRCDIR'"
  cat <<'LAUNCHER_EOF'
TAB=$(printf '\t')

if [ "$MODE" = latest ]; then
  # Candidates are exactly "STEM.app" or "STEM <digit>...app". The launcher is
  # named with no spaces ("STEMAgain.app") so it never matches itself. Sort on the NAME only, version-aware
  # (3.10.0 beats 3.5.2), then take the last.
  APP=$(
    for dir in /Applications "$HOME/Applications" "$HINT"; do
      for a in "$dir/$STEM.app" "$dir/$STEM "[0-9]*.app; do
        [ -d "$a" ] && printf '%s\t%s\n' "${a##*/}" "$a"
      done
    done | sort -u | sort -V -t "$TAB" -k1,1 | tail -1 | cut -f2
  )
else
  APP=""; [ -d "$ORIG" ] && APP="$ORIG"
fi

if [ -z "$APP" ]; then
  osascript -e "display alert \"$STEM not found\" message \"Looked in /Applications, ~/Applications and $HINT.\""
  exit 1
fi

# -n opens a NEW instance even if one is already running.
open -n "$APP"
LAUNCHER_EOF
} > "$BIN"
chmod +x "$BIN"

# --- icon: borrow the target app's, if we can find it ------------------------
ICON=""
if ICONNAME=$(defaults read "$SRC/Contents/Info" CFBundleIconFile 2>/dev/null) && [ -n "$ICONNAME" ]; then
  case "$ICONNAME" in *.icns) ;; *) ICONNAME="$ICONNAME.icns" ;; esac
  [ -f "$SRC/Contents/Resources/$ICONNAME" ] && ICON="$SRC/Contents/Resources/$ICONNAME"
fi
if [ -n "$ICON" ]; then
  cp "$ICON" "$APP/Contents/Resources/AppIcon.icns"
  ICONKEY='  <key>CFBundleIconFile</key><string>AppIcon</string>'
else
  ICONKEY=''
fi

# Bundle identifier: letters/digits only, so it's always valid.
IDSTEM=$(printf '%s' "$STEM" | tr -cd 'A-Za-z0-9')
cat > "$APP/Contents/Info.plist" <<PLIST_EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>Again</string>
  <key>CFBundleIdentifier</key><string>tv.dubpixel.again.${IDSTEM:-app}</string>
  <key>CFBundleName</key><string>$APPNAME</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
$ICONKEY
</dict>
</plist>
PLIST_EOF

touch "$APP"
echo "$APP"
